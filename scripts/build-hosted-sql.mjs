// Builds supabase/hosted-setup.sql: every migration in order, then the menu seed, in one transaction.
// Paste that file into the Supabase dashboard (SQL Editor, New query, Run) to set up a hosted project
// without the Supabase CLI. Re-run this script whenever a migration or the seed changes:
//
//   node scripts/build-hosted-sql.mjs
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const dir = `${root}supabase/migrations/`;
const files = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();

const parts = [
  `-- OAC hosted setup. Generated by scripts/build-hosted-sql.mjs from ${files.length} migrations plus supabase/seed.sql.
-- Run it ONCE on an EMPTY Supabase project: dashboard, SQL Editor, New query, paste everything, Run.
-- Everything is one transaction: if any statement fails, nothing is applied.
-- Afterwards create the demo accounts with \`npm run demo:hosted\` (see docs/deploy.md).

begin;
`,
];
for (const f of files) {
  parts.push(`\n-- ===================== ${f} =====================\n`, await readFile(dir + f, "utf8"));
}
parts.push("\n-- ===================== supabase/seed.sql =====================\n", await readFile(`${root}supabase/seed.sql`, "utf8"));
parts.push("\ncommit;\n");

await writeFile(`${root}supabase/hosted-setup.sql`, parts.join("\n"));
console.log(`wrote supabase/hosted-setup.sql (${files.length} migrations + seed)`);
