// Downloads the menu's food photos from Wikimedia Commons into public/food and writes the lookup and
// credits used by the app. Photos and their licences are listed in scripts/food-photos.json.
//
//   node scripts/build-food-images.mjs
//
// Each photo is cropped to a square (cards show them as squares) and saved as a ~480px JPEG.
// Commons rate-limits, so downloads are paced and retried. Already-downloaded files are skipped.
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const photos = JSON.parse(await readFile(root + "scripts/food-photos.json", "utf8"));
const outDir = root + "public/food/";
await mkdir(outDir, { recursive: true });

const UA = "OAC-canteen-menu/1.0 (student project; github.com/Clay1880/OAC)";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function download(title) {
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(title)}?width=640`;
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": UA }, redirect: "follow" });
      if (res.ok) return Buffer.from(await res.arrayBuffer());
    } catch {
      // connection reset: fall through to the backoff
    }
    await sleep(6000 * (attempt + 1));
  }
  throw new Error(`could not download ${title}`);
}

for (const [key, photo] of Object.entries(photos)) {
  const file = `${outDir}${key}.jpg`;
  if (existsSync(file)) continue;
  const buf = await download(photo.title);
  await sharp(buf).resize(480, 480, { fit: "cover", position: "attention" }).jpeg({ quality: 82, mozjpeg: true }).toFile(file);
  console.log("saved", key);
  await sleep(1200);
}

